// Turns the extracted facts into Markdown reference pages under docs/generated/.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from '../lib/ts-utils.mjs';

const OUT = join(ROOT, 'docs', 'generated');
const NOTICE = 'Generated by `npm run docs` from the source code. Do not edit this page by hand.';
const none = (items) => (items.length === 0 ? 'None' : items.join(', '));
const yesNo = (value) => (value ? 'Yes' : 'No');

function page(description, title, intro, body) {
  return `---\ndescription: ${description}\n---\n\n# ${title}\n\n${NOTICE}\n\n${intro}\n\n${body.join('\n\n')}\n`;
}

function table(headers, rows) {
  const head = `| ${headers.join(' | ')} |`;
  const rule = `| ${headers.map(() => '---').join(' | ')} |`;
  return [head, rule, ...rows.map((row) => `| ${row.join(' | ')} |`)].join('\n');
}

export function endpointsPage(endpoints) {
  const rows = endpoints.map((e) => [
    e.method,
    `\`${e.path}\``,
    e.access,
    String(e.status),
    e.body ? `\`${e.body}\`` : 'None',
    `\`${e.handler}\``,
  ]);
  return page(
    'Every HTTP endpoint of the API with its method, access rule, success status and body schema, generated from the controllers.',
    'HTTP endpoints',
    'The access column names who may call the endpoint. `public` needs no token. `any signed-in user` needs a valid access token. `admin` needs a token for a user with the `admin` role.',
    [table(['Method', 'Path', 'Access', 'Success status', 'Body schema', 'Handler'], rows)],
  );
}

export function configurationPage(variables) {
  const rows = variables.map((v) => [
    `\`${v.name}\``,
    yesNo(v.required),
    v.defaultValue ? `\`${v.defaultValue}\`` : 'None',
    v.type,
    v.description || 'None',
  ]);
  return page(
    'Every environment variable the API reads at startup, with whether it is required, its default and its accepted values.',
    'Environment variables',
    'The API validates these variables when it starts and refuses to boot when a required one is missing or invalid. Set them in `.env` for local runs, or in the environment for Docker and production.',
    [table(['Variable', 'Required', 'Default', 'Accepted values', 'Purpose'], rows)],
  );
}

const keysOf = (column) =>
  [column.primary ? 'PK' : null, column.foreign ? 'FK' : null, column.unique ? 'UK' : null].filter(Boolean);

function tableSection(entry) {
  const columns = entry.columns.map((c) => [
    `\`${c.name}\``,
    c.type,
    yesNo(c.nullable),
    none(keysOf(c)),
    yesNo(c.hasDefault),
  ]);
  const foreignKeys = entry.foreignKeys.map(
    (fk) => `\`${fk.columns.join(', ')}\` references \`${fk.table}.${fk.foreignColumns.join(', ')}\` (on delete ${fk.onDelete})`,
  );
  const uniques = entry.uniques.map((cols) => `\`${cols.join(', ')}\``);
  const indexes = entry.indexes.map((name) => `\`${name}\``);
  const checks = entry.checks.map((name) => `\`${name}\``);
  return [
    `## \`${entry.name}\``,
    table(['Column', 'Type', 'Nullable', 'Keys', 'Has default'], columns),
    `**Foreign keys:** ${none(foreignKeys)}`,
    `**Unique constraints:** ${none(uniques)}`,
    `**Indexes:** ${none(indexes)}`,
    `**Check constraints:** ${none(checks)}`,
  ].join('\n\n');
}

export function dataModelPage(tables) {
  return page(
    'Every PostgreSQL table in the Drizzle schema, with its columns, keys, foreign keys, indexes and check constraints.',
    'Data model',
    `The schema has ${tables.length} tables. Keys: \`PK\` is the primary key, \`FK\` a foreign key and \`UK\` a unique column. Constraints that Drizzle cannot express, such as the booking exclusion constraint, are described in [Data model](../data-model.md).`,
    tables.map(tableSection),
  );
}

export function renderMarkdown(data) {
  mkdirSync(OUT, { recursive: true });
  const files = {
    'endpoints.md': endpointsPage(data.endpoints),
    'configuration.md': configurationPage(data.environment),
    'data-model.md': dataModelPage(data.tables),
  };
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(OUT, name), text);
  }
  return Object.keys(files).map((name) => join('docs', 'generated', name));
}
